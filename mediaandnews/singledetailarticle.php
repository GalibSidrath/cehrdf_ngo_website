                    <div class="article-body fs-6 lh-lg text-dark">
                        
                        <p>An unprecedented agreement was signed today in Cox's Bazar to protect critical marine breeding grounds. Over 500 local fishermen, in coordination with the <strong>Centre for Environment, Human Rights & Development Forum (CEHRDF)</strong> and the Department of Fisheries, have pledged to support the new conservation policy.</p>

                        <p>The initiative aims to halt the rapid decline of local fish populations, which has severely impacted both the coastal ecosystem and the livelihoods of communities depending on the sea. The agreement designates three major coastal areas as strict "No-Catch Zones" for a period of 60 days during the peak breeding season.</p>

                        <h3 class="fw-bold mt-5 mb-3">Community-Led Conservation</h3>
                        <p>What makes this initiative unique is that it wasn't enforced from the top down. "We realized that if we don't protect the fish now, our children will have empty nets," said Rahim Uddin, a community leader from a local fishing village. CEHRDF facilitated months of dialogue, workshops, and awareness campaigns to reach this consensus.</p>

                        <blockquote class="border-start border-4 border-primary ps-4 py-2 my-4 bg-light rounded text-muted fst-italic" style="border-color: #2b7a78 !important;">
                            "True sustainability happens when the community takes ownership of their environment. This agreement is a monumental step towards ecological balance in the Bay of Bengal." <br>
                            <span class="fw-bold text-dark mt-2 d-block">— Md. Ilias Miah, Founder & Chief Executive, CEHRDF</span>
                        </blockquote>

                        <h3 class="fw-bold mt-5 mb-3">Next Steps and Alternative Livelihoods</h3>
                        <p>To ensure that the fishermen do not suffer financially during this 60-day ban, CEHRDF has partnered with local government bodies to provide alternative livelihood support. This includes emergency food rations and short-term employment in the ongoing Coastal Reforestation Project.</p>

                        <ul>
                            <li>Distribution of relief packages to 500 registered families.</li>
                            <li>Training on sustainable fishing practices for the upcoming season.</li>
                            <li>Deployment of community watch groups to prevent illegal fishing by outsiders.</li>
                        </ul>

                        <p>The success of this pilot project will determine whether the "No-Catch Zone" model can be scaled across other vulnerable coastal regions of Bangladesh.</p>
                        
